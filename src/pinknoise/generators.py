"""Три способа превратить белый шум в шум 1/f^beta.

Теория
------
Белый шум имеет плоский спектр мощности S(f) ~ f^0. Дробный интеграл
порядка gamma умножает спектр *амплитуд* на (2*pi*f)^(-gamma), а значит
спектр *мощности* на f^(-2*gamma). Чтобы получить S(f) ~ 1/f^beta, нужно

        gamma = beta / 2.

beta = 0 -> белый, beta = 1 -> розовый, beta = 2 -> броуновский (gamma = 1 —
это обычный интеграл, то есть накопительная сумма).

Все генераторы принимают массив белого шума ``xi`` и возвращают массив той же
длины. Общий масштаб выходного сигнала произволен.
"""

from __future__ import annotations

import numpy as np
from scipy import signal

DEFAULT_FS = 44_100  # Гц, используется только для привязки оси частот


# --------------------------------------------------------------------------- #
# Способ 1: умножить спектр на f^(-beta/2)
# --------------------------------------------------------------------------- #
def pink_fft(xi: np.ndarray, beta: float, fs: float = DEFAULT_FS) -> np.ndarray:
    """Формирование спектра с помощью вещественного БПФ.

    X(f) -> X(f) * f^(-beta/2), бин постоянной составляющей обнуляется (f^-x бесконечно при f = 0),
    затем обратное БПФ. Точно в частотной области, но сигнал неявно
    периодичен (цикличен), поэтому переходного процесса в начале нет.
    """
    n = len(xi)
    X = np.fft.rfft(xi)
    f = np.fft.rfftfreq(n, d=1.0 / fs)
    H = np.zeros_like(f)
    H[1:] = f[1:] ** (-beta / 2.0)
    return np.fft.irfft(X * H, n=n)


# --------------------------------------------------------------------------- #
# Способ 2: дробный интеграл Грюнвальда-Летникова
# --------------------------------------------------------------------------- #
def gl_weights(gamma: float, n: int) -> np.ndarray:
    """Веса Грюнвальда-Летникова дробного интеграла порядка gamma.

    Это коэффициенты Тейлора функции (1 - z)^(-gamma):

        w_0 = 1,    w_k = w_{k-1} * (k - 1 + gamma) / k.

    Накопительное произведение векторизовано вместо цикла на Python.
    При больших k они убывают медленно, w_k ~ k^(gamma-1) (долгая память).
    """
    k = np.arange(1, n)
    w = np.empty(n)
    w[0] = 1.0
    w[1:] = np.cumprod((k - 1.0 + gamma) / k)
    return w


def pink_gl(xi: np.ndarray, beta: float) -> np.ndarray:
    """x_n = sum_k w_k * xi_{n-k}, вычисляется как свёртка через БПФ.

    Поскольку запись конечна, в первых отсчётах в сумме меньше n членов
    (усечённая память), поэтому начало сигнала немного искажено.
    Если это важно, передайте более длинный ``xi`` и отбросьте начало.
    """
    w = gl_weights(beta / 2.0, len(xi))
    return signal.fftconvolve(xi, w)[: len(xi)]


# --------------------------------------------------------------------------- #
# Способ 3: параллельный банк фильтров нижних частот первого порядка
# --------------------------------------------------------------------------- #
def design_exp_bank(
    beta: float,
    n_sections: int = 6,
    f_lo: float = 20.0,
    f_hi: float = 15_000.0,
    fs: float = DEFAULT_FS,
) -> tuple[np.ndarray, np.ndarray]:
    """Спроектировать сумму фильтров первого порядка  y_n = a_k y_{n-1} + b_k xi_n.

    * полюса a_k = exp(-2*pi*f_k/fs) на логарифмической сетке f_lo ... f_hi;
    * коэффициенты усиления b_k находятся методом наименьших квадратов так,
      чтобы |sum_k H_k(f)| ~ f^(-beta/2) в логарифмической области на [f_lo, f_hi]
      (положительность обеспечивается заменой b = exp(p)).

    Возвращает (a, b). Идея фильтра Келлета: каждая секция — это
    "излом" в спектре; сложение изломов на логарифмической сетке с правильными
    весами аппроксимирует прямую в логарифмических осях.
    """
    from scipy.optimize import least_squares

    fk = np.geomspace(f_lo, f_hi, n_sections)
    a = np.exp(-2.0 * np.pi * fk / fs)

    fg = np.geomspace(f_lo, f_hi, 400)            # частоты для подгонки
    z = np.exp(-2j * np.pi * fg / fs)
    Hk = 1.0 / (1.0 - a[:, None] * z[None, :])     # секции с единичным усилением
    target = np.log(fg ** (-beta / 2.0))

    def residual(log_b: np.ndarray) -> np.ndarray:
        H = (np.exp(log_b)[:, None] * Hk).sum(axis=0)
        e = np.log(np.abs(H)) - target
        return e - e.mean()                         # уровень произволен

    sol = least_squares(residual, np.zeros(n_sections))
    return a, np.exp(sol.x)


def pink_exp(xi: np.ndarray, a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Запустить каждую секцию через scipy.signal.lfilter и сложить выходы."""
    return sum(signal.lfilter([bk], [1.0, -ak], xi) for ak, bk in zip(a, b))


# --------------------------------------------------------------------------- #
# Справка: "улучшенный" розовый фильтр Пола Келлета (musicdsp.org), fs = 44.1 кГц
# --------------------------------------------------------------------------- #
# ВНИМАНИЕ: коэффициенты записаны по памяти из поста на musicdsp.org —
# пожалуйста, сверьте их с оригиналом, прежде чем ссылаться на них.
KELLETT_A = np.array([0.99886, 0.99332, 0.96900, 0.86650, 0.55000, -0.76160])
KELLETT_B = np.array([0.0555179, 0.0750759, 0.1538520, 0.3104856, 0.5329522, -0.0168980])
KELLETT_B6 = 0.115926      # дополнительный член, в оригинальном коде задержан на один отсчёт
KELLETT_DIRECT = 0.5362    # белый шум, добавляемый напрямую


def pink_kellett(xi: np.ndarray) -> np.ndarray:
    """Розовый фильтр Келлета, векторизованный через lfilter (та же математика, что и в C-коде)."""
    y = pink_exp(xi, KELLETT_A, KELLETT_B)
    y6 = np.concatenate(([0.0], xi[:-1])) * KELLETT_B6
    return y + y6 + xi * KELLETT_DIRECT