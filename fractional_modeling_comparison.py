import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit
from scipy.special import gamma

#Генерируем ключ для добавления шума
rng = np.random.default_rng(42)

#Генерация синтетических измерений
A_true = 0.02
alpha_true = 0.4
t = np.geomspace(1, 10000, 300)

def springpot(t, A, alpha):
    return A * t**alpha / gamma(1 + alpha)

y_true = springpot(t, A_true, alpha_true)
y = y_true * (1 + rng.normal(0, 0.02, size=t.size))  # 2% шума

#Первые 10% длительности
t_cut = t[0] + 0.10 * (t[-1] - t[0])
train = t <= t_cut

#Springpot: только A и alpha
p_spring, _ = curve_fit(
    springpot,
    t[train], y[train],
    p0=(A_true, 0.3),
    bounds=([0, 0.01], [np.inf, 1.0]),
    maxfev=20000,
)

#Ряд Прони для ползучести: сумма J_i * (1 - exp(-t/tau_i))
def prony(t, *params):
    n = len(params) // 2
    amplitudes = np.asarray(params[:n])
    taus = np.asarray(params[n:])
    return np.sum(
        amplitudes[:, None] * (1 - np.exp(-t[None, :] / taus[:, None])),
        axis=0,
    )

#Экстраполируем до года
year_s = 365.25 * 24 * 3600
t_plot = np.geomspace(t[0], year_s, 700)

fits = {}
for n in (1, 3, 5):
    #Начальные tau распределены по обучающему интервалу
    tau0 = np.geomspace(1, max(2, t_cut), n)
    amp0 = np.full(n, max(y[train]) / n)
    p0 = np.r_[amp0, tau0]

    lower = np.r_[np.zeros(n), np.full(n, 1e-3)]
    upper = np.r_[np.full(n, np.inf), np.full(n, year_s)]

    params, _ = curve_fit(
        prony,
        t[train], y[train],
        p0=p0,
        bounds=(lower, upper),
        maxfev=100_000,
    )
    fits[n] = params

#График
plt.figure(figsize=(10, 6))
plt.loglog(t, y, ".", ms=4, alpha=0.65, label="Синтетические измерения")
plt.loglog(t, y_true, "k--", lw=2, label="Истинная кривая")

plt.loglog(
    t_plot, springpot(t_plot, *p_spring),
    lw=2, label="Springpot, подгонка по первым 10%",
)

for n, params in fits.items():
    plt.loglog(
        t_plot, prony(t_plot, *params),
        lw=1.8, label=f"Прони, {n} экспонент",
    )

plt.axvline(t_cut, color="gray", ls=":", label=f"Граница обучения: {t_cut:.0f} с")
plt.axvline(year_s, color="red", ls="--", alpha=0.6, label="1 год")
plt.xlabel("Время, с")
plt.ylabel("Деформация ε")
plt.title("Зависимость деформации от времени")
plt.grid(True, which="both", alpha=0.25)
plt.legend()
plt.tight_layout()
plt.show()

print(f"Граница обучающего интервала: {t_cut:.1f} с")
print(f"Springpot: A={p_spring[0]:.6g}, alpha={p_spring[1]:.4f}")
print(f"Springpot, прогноз на год: ε={springpot(year_s, *p_spring):.6g}")
for n, params in fits.items():
    print(f"Прони ({n} экспонент), прогноз на год: "
          f"ε={prony(np.array([year_s]), *params)[0]:.6g}")
plt.figure(figsize=(9, 6))

plt.loglog(
    t, y,
    ".",
    ms=4,
    alpha=0.65,
    label="Синтетические измерения",
)

plt.loglog(
    t, y_true,
    "k--",
    lw=2,
    label="Истинная кривая",
)

plt.xlabel("Время, с")
plt.ylabel("Деформация ε")
plt.title("Синтетические измерения и истинная кривая")
plt.grid(True, which="both", alpha=0.25)
plt.legend()
plt.tight_layout()
plt.show()